def auto_entry(t, keypos, old):
    """form_auto: 기존 법령 프리셋(pickers law)은 유지하고, 작업 예시를 덧붙인다."""
    a = dict(old or {})
    a["profile"] = {"f.chief": "sup"}
    if not t.get("date_text"):
        a["today"] = ["f.date"]
    else:
        a.pop("today", None)
    pk = [p for p in a.get("pickers", []) if p.get("id") == "law"]
    opts = []
    for e in t.get("ex", []):
        o = dict(label=e["label"], rows={})
        for k in ("steps", "risk", "res", "mach"):
            if k in e: o["rows"][k] = e[k]
        if "byl4" in e:
            o["rows"]["byl4"] = [[None, r[1], (r[2] if t.get("byl4_detail") else (f"→ {keypos[r[2]]}번" if r[2] in keypos else r[2]))] for r in e["byl4"]]
            o["rows"]["byl4"] = [["" if c is None else c for c in r] for r in o["rows"]["byl4"]]
        if "route" in e: o["set"] = {"x.route": e["route"]}
        opts.append(o)
    if opts:
        pk.append(dict(id="ex", replace=True, label="작업 예시", button="예시 채우기",
                       hint="작업순서·위험요인·장비 표에 예시가 들어갑니다. 예시는 SafePlum이 기준규칙 조문을 바탕으로 만든 일반 예시입니다. 반드시 현장 조사 결과로 고쳐 쓰세요.", options=opts))
    a["pickers"] = pk
    a["pick_confirm"] = "이미 입력한 표 내용 일부가 예시 문구로 바뀝니다. 계속할까요?"
    ai = dict(a.get("ai") or {})
    ai["ask"] = "작업 내용을 적어 주세요(무엇을·어디서·어떤 장비로·몇 명이)"
    if EXS.get(t["id"]):
        ai["example"] = EXS[t["id"]][0]
    ai["system"] = ("작업계획서(산업안전보건기준에 관한 규칙 제38조, 별표 4 제" + t["no"] + "호)를 쓴다. 별표 4 포함사항 반영표의 '계획 반영 내용'은 항목마다 이 작업에 맞는 구체적인 방법으로 한 줄씩 채운다. "
                    "작업순서표는 실제 작업 흐름대로 단계별 주요 위험과 통제 방법을 쓰고, 위험요인 표의 예방대책 끝에는 근거 조문을 괄호로 붙인다(제공된 조문에 있는 번호만). "
                    "성명·날짜·인원수·장비 번호·측정값·점검 결과(적합/양호 등)는 채우지 않는다.")
    kw = ["작업계획서", "사전조사", "별표 4"] + [t["short"].split("·")[0]]
    ai["examples"] = EXS.get(t["id"], [])[1:]
    ai["keywords"] = list(dict.fromkeys((ai.get("keywords") or []) + kw))
    ai["skip"] = list(dict.fromkeys((ai.get("skip") or []) + ["f.svy_date", "f.svy_by", "f.crew", "f.reg"]))
    a["ai"] = ai
    return a


